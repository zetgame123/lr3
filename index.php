<h2>Фотография дня</h2>

<p>Ниже находится фотография, которая выбирается автоматически при загрузке страницы. Если текущая секунда чётная, выводится первый файл, если нечётная — второй. Достаточно обновить страницу через секунду, и на этом же месте появится другое изображение. Такой простой пример показывает, что содержимое страницы может зависеть от условий, а не быть заранее записанным в HTML-файл.</p>

<?php
$s = date('s');          // определяем текущую секунду
$os = $s % 2;            // вычисляем остаток от деления


if ($os === 0)           // если в переменной $os хранится ноль
    $name = 'fotos/foto1.jpg';   // сохраняем имя первого файла
else                     // иначе
    $name = 'fotos/foto2.jpg';   // сохраняем имя второго файла

echo '<img class="photo" src="' . $name . '" alt="Меняющаяся фотография">';
?>

